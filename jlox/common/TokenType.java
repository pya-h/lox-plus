package jlox.common;

public enum TokenType {
    // Single-character tokens.
    LEFT_PAREN,
    RIGHT_PAREN,
    LEFT_BRACE,
    RIGHT_BRACE,
    LEFT_BRACKET,
    RIGHT_BRACKET,
    COMMA,
    DOT,
    MINUS,
    PLUS,
    SEMICOLON,
    FORTH_SLASH,
    BACK_SLASH,
    STAR,
    PERCENTAGE,
    QUOTATION,
    DOUBLE_QUOTATION,
    QUESTION,

    // One or two character tokens.
    BANG,
    BANG_EQUAL,
    EQUAL,
    EQUAL_EQUAL,
    GREATER,
    GREATER_EQUAL,
    LESS,
    LESS_EQUAL,
    TILDE,

    // Literals.
    IDENTIFIER,
    STRING,
    NUMBER,

    // Keywords.
    AND,
    NAND,
    CLASS,
    ELSE,
    FALSE,
    FX,
    FOR,
    IF,
    NIL,
    OR,
    XOR,
    PRINT,
    RETURN,
    PARENT,
    THIS,
    TRUE,
    LX,
    LOOP,
    BACKWARD,
    JUMP,
    JUMP_TYPE_OUT,
    JUMP_TYPE_NEXT,
    EOF,
}
